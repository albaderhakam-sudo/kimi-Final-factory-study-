export function t(key, lang, ...args) {
  const L = I18N[lang] || I18N["en"];
  let s = key in L ? L[key] : key in I18N.en ? I18N.en[key] : key;
  for (let i = 0; i < args.length; i++) {
    s = s.split("{" + i + "}").join(args[i]);
  }
  return s;
}

export function tBilingual(key, ...args) {
  const en = t(key, "en", ...args);
  const zh = t(key, "zh", ...args);
  if (en === zh) return en;
  return en + " / " + zh;
}
